const DefaultConfigFilename = "oruby.yml"

// OrubyConfig represents the declarative configuration in oruby.yml.
type OrubyConfig struct {
	Name        string           `yaml:"name"`
	Output      string           `yaml:"output"`
	Entrypoint  string           `yaml:"entrypoint"`
	Target      string           `yaml:"target"` // "orb" (default), "exe", "dev" or "native"
	Compiler    CompilerConfig   `yaml:"compiler"`
	Gems        GemsConfig       `yaml:"gems"`
	Extensions  ExtensionsConfig `yaml:"extensions"`
	Include     []string         `yaml:"include"`
	EmbedPublic bool             `yaml:"embed_public"`
	Filters     FiltersConfig    `yaml:"filters"`
}

// ExtensionsConfig controls whether project gems compile their upstream C
// extensions (via gem/capi) or link opt-in Go extensions from goext/.
type ExtensionsConfig struct {
	Mode string   `yaml:"mode"` // "c" (default), "go", or "auto"
	Go   []string `yaml:"go"`   // explicit per-gem Go extension overrides
	C    []string `yaml:"c"`    // explicit per-gem C extension overrides (when mode: go)
}

type CompilerConfig struct {
	DebugInfo  bool     `yaml:"debug_info"`
	RemoveLv   bool     `yaml:"remove_lv"`
	NoExtOps   bool     `yaml:"no_ext_ops"`
	NoOptimize bool     `yaml:"no_optimize"`
	RBS        []string `yaml:"rbs"`
	CheckRBS   bool     `yaml:"check_rbs"`
}

type GemsConfig struct {
	Enabled bool     `yaml:"enabled"`
	Gemfile string   `yaml:"gemfile"`
	Groups  []string `yaml:"groups"`
}

type FiltersConfig struct {
	SkipDotfiles     bool     `yaml:"skip_dotfiles"`
	RespectGitignore bool     `yaml:"respect_gitignore"`
	Exclude          []string `yaml:"exclude"`
}

// DefaultOrubyConfig generates a project-tailored default configuration for projectDir.
func DefaultOrubyConfig(projectDir string) *OrubyConfig {
	absDir, err := filepath.Abs(projectDir)
	if err != nil || absDir == "" {
		absDir = "."
	}
	appName := filepath.Base(absDir)
	if appName == "." || appName == "/" || appName == "" {
		appName = "app"
	}

	isRails := false
	if fi, err := os.Stat(filepath.Join(absDir, "config", "application.rb")); err == nil && !fi.IsDir() {
		isRails = true
	}

	hasGemfile := false
	if fi, err := os.Stat(filepath.Join(absDir, "Gemfile")); err == nil && !fi.IsDir() {
		hasGemfile = true
	}

	entrypoint := ""
	var includeList []string
	if isRails {
		for _, cand := range []string{"bin/rails", "config.ru", "run.rb", "app.rb", "config/environment.rb"} {
			if fi, err := os.Stat(filepath.Join(absDir, filepath.FromSlash(cand))); err == nil && !fi.IsDir() {
				entrypoint = cand
				break
			}
		}
		if entrypoint == "" {
			entrypoint = "config/environment.rb"
		}
		for _, item := range []string{
			"app",
			"bin",
			"config",
			"db/migrate",
			"db/schema.rb",
			"db/seeds.rb",
			"lib",
			"Gemfile",
			"Gemfile.lock",
			"Rakefile",
			"config.ru",
			"run.rb",
		} {
			if _, err := os.Stat(filepath.Join(absDir, filepath.FromSlash(item))); err == nil {
				includeList = append(includeList, item)
			}
		}
		if len(includeList) == 0 {
			includeList = []string{"app", "bin", "config", "lib", "Gemfile", "Gemfile.lock", "config.ru"}
		}
	} else {
		for _, cand := range []string{"app.rb", "main.rb", "run.rb", "config.ru", "bin/" + appName} {
			if fi, err := os.Stat(filepath.Join(absDir, filepath.FromSlash(cand))); err == nil && !fi.IsDir() {
				entrypoint = cand
				break
			}
		}
		for _, item := range []string{"app", "bin", "config", "lib", "Gemfile", "Gemfile.lock", "Rakefile", "config.ru", "app.rb", "main.rb", "run.rb"} {
			if _, err := os.Stat(filepath.Join(absDir, filepath.FromSlash(item))); err == nil {
				includeList = append(includeList, item)
			}
		}
		if len(includeList) == 0 {
			includeList = []string{"lib", "app"}
		}
	}

	return &OrubyConfig{
		Name:       appName,
		Output:     "build/" + appName + ".orb",
		Entrypoint: entrypoint,
		Target:     "orb",
		Compiler: CompilerConfig{
			DebugInfo: true,
			RemoveLv:  false,
		},
		Gems: GemsConfig{
			Enabled: hasGemfile || isRails,
			Gemfile: "Gemfile",
			Groups:  []string{"default", "production"},
		},
		Extensions: ExtensionsConfig{
			Mode: "c",
		},
		Include:     includeList,
		EmbedPublic: false,
		Filters: FiltersConfig{
			SkipDotfiles:     true,
			RespectGitignore: true,
			Exclude: []string{
				"config/master.key",
				"config/credentials/*.key",
				"*.pem",
				"*.key",
				".env*",
				"log/**",
				"storage/**",
				"tmp/**",
				"test/**",
				"spec/**",
				"vendor/**",
				"node_modules/**",
				"db/*.sqlite3*",
				"build/**",
			},
		},
	}
}

// RenderOrubyYAML formats cfg as a well-commented oruby.yml file.
func RenderOrubyYAML(cfg *OrubyConfig) string {
	var b strings.Builder
	b.WriteString("# ORuby Application Build & Bundle Configuration\n")
	b.WriteString("# Generated by `oruby init`. Run `oruby build` to compile.\n\n")
	fmt.Fprintf(&b, "name: %s\n", cfg.Name)
	fmt.Fprintf(&b, "output: %s\n", cfg.Output)
	fmt.Fprintf(&b, "entrypoint: %s\n", cfg.Entrypoint)
	fmt.Fprintf(&b, "target: %s # \"orb\" (RiteVM bytecode archive), \"exe\" (one executable: oruby, the gems' C\n"+
		"            # extensions and the archive), \"dev\" (bin/oruby with the C extensions) or \"native\" (Go AOT)\n\n", cfg.Target)

	b.WriteString("compiler:\n")
	fmt.Fprintf(&b, "  debug_info: %v # Keep file/line info for backtraces\n", cfg.Compiler.DebugInfo)
	fmt.Fprintf(&b, "  remove_lv: %v  # Strip local variable symbol tables for smaller size\n\n", cfg.Compiler.RemoveLv)

	b.WriteString("gems:\n")
	fmt.Fprintf(&b, "  enabled: %v\n", cfg.Gems.Enabled)
	fmt.Fprintf(&b, "  gemfile: %s\n", cfg.Gems.Gemfile)
	b.WriteString("  groups:\n")
	for _, g := range cfg.Gems.Groups {
		fmt.Fprintf(&b, "    - %s\n", g)
	}
	b.WriteString("\n")

	extMode := cfg.Extensions.Mode
	if extMode == "" {
		extMode = "c"
	}
	b.WriteString("# Native extension backend for target: dev, exe, or native:\n")
	b.WriteString("#   mode: \"c\" (default: compile C extensions via gem/capi), \"go\" (prefer goext/ Go\n")
	b.WriteString("#         replacements), or \"auto\" (try C first, fall back to Go if extconf fails)\n")
	b.WriteString("extensions:\n")
	fmt.Fprintf(&b, "  mode: %s\n", extMode)
	if len(cfg.Extensions.Go) > 0 {
		b.WriteString("  go:\n")
		for _, g := range cfg.Extensions.Go {
			fmt.Fprintf(&b, "    - %s\n", g)
		}
	} else {
		b.WriteString("  # go: [pg, ruby-vips, zstd-ruby]\n")
	}
	if len(cfg.Extensions.C) > 0 {
		b.WriteString("  c:\n")
		for _, c := range cfg.Extensions.C {
			fmt.Fprintf(&b, "    - %s\n", c)
		}
	}
	b.WriteString("\n")

	b.WriteString("# Explicit allowlist of directories and files to compile & pack into the bundle\n")
	b.WriteString("include:\n")
	for _, inc := range cfg.Include {
		fmt.Fprintf(&b, "  - %s\n", inc)
	}
	b.WriteString("\n")

	b.WriteString("# Public static assets (public/):\n")
	b.WriteString("# false = keep public/ standalone on disk (for Nginx/CDN/pre-gzipped serving)\n")
	b.WriteString("# true  = embed public/ inside the .orb virtual filesystem for single-file deploys\n")
	fmt.Fprintf(&b, "embed_public: %v\n\n", cfg.EmbedPublic)

	b.WriteString("# Hygiene and security filters applied when scanning included directories\n")
	b.WriteString("filters:\n")
	fmt.Fprintf(&b, "  skip_dotfiles: %v     # Skip all hidden \".*\" files and folders (.git, .env, .claude, etc.)\n", cfg.Filters.SkipDotfiles)
	fmt.Fprintf(&b, "  respect_gitignore: %v # Skip files matched by .gitignore\n", cfg.Filters.RespectGitignore)
	b.WriteString("  exclude:\n")
	for _, ex := range cfg.Filters.Exclude {
		fmt.Fprintf(&b, "    - %q\n", ex)
	}
	return b.String()
}

// RenderDockerfile generates a two-stage Alpine Dockerfile for the ORuby project.
func RenderDockerfile(cfg *OrubyConfig) string {
	orbOut := cfg.Output
	if orbOut == "" {
		orbOut = "build/" + cfg.Name + ".orb"
	}
	orbOut = filepath.ToSlash(orbOut)
	outDir := filepath.Dir(orbOut)
	binOut := filepath.ToSlash(filepath.Join(outDir, "bin"))
	libOut := filepath.ToSlash(filepath.Join(outDir, "lib"))

	publicCopy := "# COPY --from=builder /src/public /app/public"
	if !cfg.EmbedPublic {
		publicCopy = "COPY --from=builder /src/public /app/public"
	}

	return fmt.Sprintf(`# syntax=docker/dockerfile:1
# Generated by 'oruby init --docker'

# Stage 1: Build the .orb bundle and gather target-platform gem binaries & shared libraries
FROM alpine:3.21 AS builder
RUN apk add --no-cache ca-certificates

WORKDIR /src

# Provide the target-platform oruby binary (e.g. built for Linux/Alpine)
COPY bin/oruby /usr/local/bin/oruby

# Optional: if Gemfile includes platform-specific gems (e.g. thruster), install
# target-platform gems in the builder stage before running 'oruby build':
# RUN apk add --no-cache ruby ruby-bundler && bundle config set --local without 'development test' && bundle install

COPY . .
RUN mkdir -p %s %s && /usr/local/bin/oruby build

# Stage 2: Minimal runtime image with compiled .orb, runtime, binaries, and supporting files
FROM alpine:3.21 AS runtime
RUN apk add --no-cache ca-certificates tzdata

WORKDIR /app

COPY --from=builder /usr/local/bin/oruby /usr/local/bin/oruby
COPY --from=builder /src/%s /app/%s.orb
COPY --from=builder /src/%s/ /app/bin/
COPY --from=builder /src/%s/ /app/lib/
%s

ENV PATH="/app/bin:${PATH}" \
    LD_LIBRARY_PATH="/app/lib" \
    RAILS_ENV=production
# Pass RAILS_MASTER_KEY at runtime via Docker environment / secrets:
# docker run -e RAILS_MASTER_KEY=... -p 3000:3000 %s

EXPOSE 3000
CMD ["/usr/local/bin/oruby", "/app/%s.orb"]
# If using Thruster (gathered into /app/bin/thrust):
# CMD ["/app/bin/thrust", "/usr/local/bin/oruby", "/app/%s.orb"]
`, binOut, libOut, orbOut, cfg.Name, binOut, libOut, publicCopy, cfg.Name, cfg.Name, cfg.Name)
}

// LoadOrubyConfig reads and parses an oruby.yml file, filling in sensible defaults for unset fields.
func LoadOrubyConfig(configPath string) (*OrubyConfig, error) {
	data, err := os.ReadFile(configPath)
	if err != nil {
		return nil, err
	}
	projectDir := filepath.Dir(configPath)
	cfg := DefaultOrubyConfig(projectDir)
	// Clear slice fields before unmarshaling so user lists replace defaults if specified
	defaultInclude := cfg.Include
	defaultExclude := cfg.Filters.Exclude
	defaultGroups := cfg.Gems.Groups
	cfg.Include = nil
	cfg.Filters.Exclude = nil
	cfg.Gems.Groups = nil

	if err := yamllib.Unmarshal(data, cfg); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", configPath, err)
	}
	if len(cfg.Include) == 0 {
		cfg.Include = defaultInclude
	}
	if len(cfg.Filters.Exclude) == 0 {
		cfg.Filters.Exclude = defaultExclude
	}
	if len(cfg.Gems.Groups) == 0 {
		cfg.Gems.Groups = defaultGroups
	}
	if cfg.Target == "" {
		cfg.Target = "orb"
	}
	if cfg.Extensions.Mode == "" {
		cfg.Extensions.Mode = "c"
	}
	if cfg.Output == "" {
		cfg.Output = "build/" + cfg.Name + ".orb"
	}
	return cfg, nil
}

type gitignoreRule struct {
	pattern  string
	negated  bool
	dirOnly  bool
	anchored bool
}

func loadGitignoreRules(gitignorePath string) []gitignoreRule {
	data, err := os.ReadFile(gitignorePath)
	if err != nil {
		return nil
	}
	var rules []gitignoreRule
	for _, raw := range strings.Split(string(data), "\n") {
		line := strings.TrimSpace(strings.TrimRight(raw, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		neg := false
		if strings.HasPrefix(line, "!") {
			neg = true
			line = strings.TrimPrefix(line, "!")
		}
		dirOnly := false
		if strings.HasSuffix(line, "/") {
			dirOnly = true
			line = strings.TrimSuffix(line, "/")
		}
		anchored := false
		if strings.HasPrefix(line, "/") {
			anchored = true
			line = strings.TrimPrefix(line, "/")
		} else if strings.Contains(line, "/") {
			anchored = true
		}
		if line == "" {
			continue
		}
		rules = append(rules, gitignoreRule{
			pattern:  line,
			negated:  neg,
			dirOnly:  dirOnly,
			anchored: anchored,
		})
	}
	return rules
}

// matchGlobPattern matches a forward-slash relative path against a pattern supporting *, ?, and **.
func matchGlobPattern(pattern, relSlash string) bool {
	pattern = strings.TrimPrefix(filepath.ToSlash(pattern), "/")
	relSlash = strings.TrimPrefix(filepath.ToSlash(relSlash), "/")
	if pattern == "" {
		return false
	}
	if strings.HasSuffix(pattern, "/**") {
		prefix := strings.TrimSuffix(pattern, "/**")
		return relSlash == prefix || strings.HasPrefix(relSlash, prefix+"/")
	}
	if strings.Contains(pattern, "**") {
		parts := strings.SplitN(pattern, "**", 2)
		pre := strings.TrimSuffix(parts[0], "/")
		suf := strings.TrimPrefix(parts[1], "/")
		if pre != "" && relSlash != pre && !strings.HasPrefix(relSlash, pre+"/") {
			return false
		}
		if suf == "" {
			return true
		}
		if ok, _ := path.Match(suf, path.Base(relSlash)); ok {
			return true
		}
		if ok, _ := path.Match(suf, relSlash); ok {
			return true
		}
		return false
	}
	if ok, _ := path.Match(pattern, relSlash); ok {
		return true
	}
	if strings.HasPrefix(relSlash, pattern+"/") {
		return true
	}
	if !strings.Contains(pattern, "/") {
		if ok, _ := path.Match(pattern, path.Base(relSlash)); ok {
			return true
		}
	}
	return false
}

// shouldExcludeRelPath evaluates dotfile, .gitignore, and exclude list rules for a relative path inside projectDir.
func shouldExcludeRelPath(relSlash string, isDir bool, cfg *OrubyConfig, gitRules []gitignoreRule) bool {
	relSlash = oruby.NormalizeOrbPath(relSlash)
	if relSlash == "" {
		return false
	}

	// Never pack the config file itself or Dockerfile into the .orb
	if relSlash == DefaultConfigFilename || strings.HasPrefix(relSlash, "Dockerfile") {
		return true
	}

	// 1. Check dotfile filter (hidden ".*" files and directories)
	if cfg.Filters.SkipDotfiles {
		for _, seg := range strings.Split(relSlash, "/") {
			if strings.HasPrefix(seg, ".") && seg != "." && seg != ".." {
				return true
			}
		}
	}

	// 2. Check explicit exclude globs in oruby.yml
	for _, pat := range cfg.Filters.Exclude {
		if matchGlobPattern(pat, relSlash) {
			return true
		}
	}

	// 3. Check .gitignore rules if enabled
	if cfg.Filters.RespectGitignore && len(gitRules) > 0 {
		ignored := false
		for _, r := range gitRules {
			if r.dirOnly && !isDir {
				// Still check if a parent directory matched r.pattern
				if !strings.HasPrefix(relSlash, r.pattern+"/") {
					continue
				}
			}
			matched := false
			if r.anchored {
				matched = matchGlobPattern(r.pattern, relSlash)
			} else {
				if ok, _ := path.Match(r.pattern, path.Base(relSlash)); ok {
					matched = true
				} else if matchGlobPattern(r.pattern, relSlash) {
					matched = true
				}
			}
			if matched {
				ignored = !r.negated
			}
		}
		if ignored {
			return true
		}
	}

	return false
}

// runInitSubcommand implements `oruby init` / `orubyc init`.
func runInitSubcommand(args []string) int {
	projectDir := "."
	configFile := DefaultConfigFilename
	force := false
	genDocker := false

	for i := 0; i < len(args); i++ {
		a := args[i]
		switch {
		case a == "-f" || a == "--force":
			force = true
		case a == "--docker" || a == "-d":
			genDocker = true
		case a == "-c" || a == "--config":
			if i+1 < len(args) {
				i++
				configFile = args[i]
			}
		case strings.HasPrefix(a, "--config="):
			configFile = strings.TrimPrefix(a, "--config=")
		case !strings.HasPrefix(a, "-"):
			projectDir = a
		}
	}

	absDir, err := filepath.Abs(projectDir)
	if err != nil {
		return exitFailure("oruby init: invalid directory %s: %v\n", projectDir, err)
	}
	if !filepath.IsAbs(configFile) {
		configFile = filepath.Join(absDir, configFile)
	}

	if !force {
		if _, err := os.Stat(configFile); err == nil {
			return exitFailure("oruby init: %s already exists (use --force to overwrite)\n", configFile)
		}
	}

	cfg := DefaultOrubyConfig(absDir)
	content := RenderOrubyYAML(cfg)
	if err := os.WriteFile(configFile, []byte(content), 0644); err != nil {
		return exitFailure("oruby init: failed to write %s: %v\n", configFile, err)
	}
	fmt.Printf("Created %s (project: %s, output: %s)\n", configFile, cfg.Name, cfg.Output)

	if genDocker {
		dockerPath := filepath.Join(absDir, "Dockerfile.oruby")
		if err := os.WriteFile(dockerPath, []byte(RenderDockerfile(cfg)), 0644); err != nil {
			return exitFailure("oruby init: failed to write %s: %v\n", dockerPath, err)
		}
		fmt.Printf("Created %s\n", dockerPath)
	}
	return 0
}

// runBuildSubcommand implements `oruby build` / `orubyc build`.
func runBuildSubcommand(mrb *oruby.MrbState, prog string, args []string) int {
	configFile := DefaultConfigFilename
	var overrideOutput, overrideEntry, overrideTarget string
	var overrideExtMode string
	var overrideGoExts, overrideCExts, overrideRBS []string
	var overrideCheckRBS bool
	var overrideEmbedPublic, hasEmbedPublic bool
	var overrideNoGems, verbose bool

	appendCSV := func(dst []string, raw string) []string {
		for _, item := range strings.Split(raw, ",") {
			if s := strings.TrimSpace(item); s != "" {
				dst = append(dst, s)
			}
		}
		return dst
	}

	for i := 0; i < len(args); i++ {
		a := args[i]
		switch {
		case a == "-c" || a == "--config":
			if i+1 < len(args) {
				i++
				configFile = args[i]
			}
		case strings.HasPrefix(a, "--config="):
			configFile = strings.TrimPrefix(a, "--config=")
		case a == "-o" || a == "--output" || a == "--orb":
			if i+1 < len(args) {
				i++
				overrideOutput = args[i]
			}
		case strings.HasPrefix(a, "--output="):
			overrideOutput = strings.TrimPrefix(a, "--output=")
		case strings.HasPrefix(a, "--orb="):
			overrideOutput = strings.TrimPrefix(a, "--orb=")
		case a == "--entry" || a == "--entrypoint":
			if i+1 < len(args) {
				i++
				overrideEntry = args[i]
			}
		case strings.HasPrefix(a, "--entry="):
			overrideEntry = strings.TrimPrefix(a, "--entry=")
		case strings.HasPrefix(a, "--entrypoint="):
			overrideEntry = strings.TrimPrefix(a, "--entrypoint=")
		case a == "--target":
			if i+1 < len(args) {
				i++
				overrideTarget = args[i]
			}
		case strings.HasPrefix(a, "--target="):
			overrideTarget = strings.TrimPrefix(a, "--target=")
		case a == "--ext-mode":
			if i+1 < len(args) {
				i++
				overrideExtMode = args[i]
			}
		case strings.HasPrefix(a, "--ext-mode="):
			overrideExtMode = strings.TrimPrefix(a, "--ext-mode=")
		case a == "--go-ext":
			if i+1 < len(args) {
				i++
				overrideGoExts = appendCSV(overrideGoExts, args[i])
			}
		case strings.HasPrefix(a, "--go-ext="):
			overrideGoExts = appendCSV(overrideGoExts, strings.TrimPrefix(a, "--go-ext="))
		case a == "--c-ext":
			if i+1 < len(args) {
				i++
				overrideCExts = appendCSV(overrideCExts, args[i])
			}
		case strings.HasPrefix(a, "--c-ext="):
			overrideCExts = appendCSV(overrideCExts, strings.TrimPrefix(a, "--c-ext="))
		case a == "--rbs":
			if i+1 < len(args) {
				i++
				overrideRBS = appendCSV(overrideRBS, args[i])
			}
		case strings.HasPrefix(a, "--rbs="):
			overrideRBS = appendCSV(overrideRBS, strings.TrimPrefix(a, "--rbs="))
		case a == "--check-rbs":
			overrideCheckRBS = true
		case a == "--embed-public":
			overrideEmbedPublic = true
			hasEmbedPublic = true
		case a == "--no-embed-public":
			overrideEmbedPublic = false
			hasEmbedPublic = true
		case a == "--no-gems":
			overrideNoGems = true
		case a == "-v" || a == "--verbose":
			verbose = true
		case !strings.HasPrefix(a, "-"):
			if fi, err := os.Stat(a); err == nil && fi.IsDir() {
				configFile = filepath.Join(a, DefaultConfigFilename)
			} else {
				configFile = a
			}
		}
	}

	absConfig, err := filepath.Abs(configFile)
	if err != nil {
		absConfig = configFile
	}
	projectDir := filepath.Dir(absConfig)

	var cfg *OrubyConfig
	if _, stErr := os.Stat(absConfig); stErr == nil {
		cfg, err = LoadOrubyConfig(absConfig)
		if err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
	} else {
		// If oruby.yml doesn't exist yet, use default project config in projectDir
		cfg = DefaultOrubyConfig(projectDir)
	}

	if overrideOutput != "" {
		cfg.Output = overrideOutput
	}
	if overrideEntry != "" {
		cfg.Entrypoint = overrideEntry
	}
	if overrideTarget != "" {
		cfg.Target = overrideTarget
	}
	if overrideExtMode != "" {
		cfg.Extensions.Mode = overrideExtMode
	}
	if len(overrideGoExts) > 0 {
		cfg.Extensions.Go = append(cfg.Extensions.Go, overrideGoExts...)
	}
	if len(overrideCExts) > 0 {
		cfg.Extensions.C = append(cfg.Extensions.C, overrideCExts...)
	}
	if len(overrideRBS) > 0 {
		cfg.Compiler.RBS = append(cfg.Compiler.RBS, overrideRBS...)
	}
	if overrideCheckRBS {
		cfg.Compiler.CheckRBS = true
	}
	if hasEmbedPublic {
		cfg.EmbedPublic = overrideEmbedPublic
	}
	if overrideNoGems {
		cfg.Gems.Enabled = false
	}

	pol, err := newExtPolicy(cfg.Extensions)
	if err != nil {
		return exitFailure("%s build: %v\n", prog, err)
	}

	// target: orb produces a bytecode archive for stock standalone oruby and
	// cannot link Go extensions from goext/.
	isOrbTarget := strings.EqualFold(cfg.Target, "orb") || cfg.Target == ""
	if isOrbTarget && (pol.Mode == "go" || len(pol.ExplicitGo) > 0) {
		return exitFailure("%s build: Go extensions require target: dev, exe, or native (not %q)\n", prog, cfg.Target)
	}

	// dev: the project's bin/oruby, ORuby with the gems' C and Go extensions
	// compiled in, running the project from its files (binary.go)
	if strings.EqualFold(cfg.Target, "dev") {
		out := overrideOutput
		if out == "" {
			out = filepath.Join("bin", "oruby")
		}
		if !filepath.IsAbs(out) {
			out = filepath.Join(projectDir, filepath.FromSlash(out))
		}
		if err := buildProjectBinary(prog, projectDir, cfg, nil, pol, "", out, verbose); err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
		fmt.Printf("Built %s\n", out)
		return 0
	}
	outPath := cfg.Output
	if !filepath.IsAbs(outPath) {
		outPath = filepath.Join(projectDir, filepath.FromSlash(outPath))
	}
	absOut, _ := filepath.Abs(outPath)

	var hdrFlags uint16
	var dumpFlags uint8
	if cfg.Compiler.DebugInfo {
		hdrFlags |= oruby.OrbHdrDebugInfo
		dumpFlags |= oruby.MrbDumpDebugInfo
	}
	if cfg.Compiler.RemoveLv {
		dumpFlags |= oruby.MrbDumpNoLvar
	}

	mArgs := &mrbcArgs{
		prog:       prog,
		orbfile:    absOut,
		entrypoint: cfg.Entrypoint,
		verbose:    verbose,
		removeLv:   cfg.Compiler.RemoveLv,
		noExtOps:   cfg.Compiler.NoExtOps,
		noOptimize: cfg.Compiler.NoOptimize,
		flags:      dumpFlags,
	}

	builder := oruby.NewOrbBuilder(hdrFlags)
	if cfg.Entrypoint != "" {
		builder.SetEntrypoint(cfg.Entrypoint)
	}

	var gitRules []gitignoreRule
	if cfg.Filters.RespectGitignore {
		gitRules = loadGitignoreRules(filepath.Join(projectDir, ".gitignore"))
	}

	packFileWithVirtual := func(inPath, vpath string) error {
		if absIn, err := filepath.Abs(inPath); err == nil && absIn == absOut {
			return nil
		}
		if vpath == "" {
			return nil
		}
		return packSingleFileIntoOrb(mrb, builder, inPath, vpath, mArgs)
	}

	// 1. Resolve and pack Gemfile gems for the configured groups
	var packedGems []*resolvedGemDir
	if cfg.Gems.Enabled {
		gemfile := cfg.Gems.Gemfile
		if gemfile == "" {
			gemfile = "Gemfile"
		}
		if !filepath.IsAbs(gemfile) {
			gemfile = filepath.Join(projectDir, filepath.FromSlash(gemfile))
		}
		if fi, err := os.Stat(gemfile); err == nil && !fi.IsDir() {
			packedGems, err = packGemfileGemsWithPolicy(mrb, builder, gemfile, projectDir, cfg.Gems.Groups, pol, mArgs, packFileWithVirtual)
			if err != nil {
				return exitFailure("%s build: %v\n", prog, err)
			}
			if isOrbTarget {
				var nativeGems []string
				for _, g := range packedGems {
					if len(gemExtensions(g)) > 0 || hasNonExtconfExtensions(g) {
						nativeGems = append(nativeGems, g.Name+"-"+g.Version)
					}
				}
				if len(nativeGems) > 0 {
					fmt.Fprintf(os.Stderr, "%s build: warning: gems with native extensions are not compiled into .orb (%s); install them on the target host or use --target=exe / --target=native\n",
						prog, strings.Join(nativeGems, ", "))
				}
			}
		}
	}

	// 2. Build the list of included roots
	includes := append([]string{}, cfg.Include...)
	if cfg.EmbedPublic {
		hasPublic := false
		for _, inc := range includes {
			if oruby.NormalizeOrbPath(inc) == "public" {
				hasPublic = true
				break
			}
		}
		if !hasPublic {
			includes = append(includes, "public")
		}
	} else {
		// Ensure public is not in includes unless embed_public is true
		filtered := make([]string, 0, len(includes))
		for _, inc := range includes {
			norm := oruby.NormalizeOrbPath(inc)
			if norm == "public" || strings.HasPrefix(norm, "public/") {
				continue
			}
			filtered = append(filtered, inc)
		}
		includes = filtered
	}

	packedFiles := 0
	for _, inc := range includes {
		normInc := oruby.NormalizeOrbPath(inc)
		if normInc == "" {
			continue
		}
		targetPath := filepath.Join(projectDir, filepath.FromSlash(normInc))
		fi, err := os.Stat(targetPath)
		if err != nil {
			if verbose {
				fmt.Fprintf(os.Stderr, "%s build: skipping missing include path %s\n", prog, normInc)
			}
			continue
		}

		if !fi.IsDir() {
			// Explicitly listed single file in `include:` is packed unless it matches an explicit exclude pattern
			excluded := false
			for _, pat := range cfg.Filters.Exclude {
				if matchGlobPattern(pat, normInc) {
					excluded = true
					break
				}
			}
			if excluded {
				continue
			}
			if err := packFileWithVirtual(targetPath, normInc); err != nil {
				return exitFailure("%s build: %v\n", prog, err)
			}
			packedFiles++
			continue
		}

		err = filepath.WalkDir(targetPath, func(p string, d os.DirEntry, wErr error) error {
			if wErr != nil {
				return wErr
			}
			rel, rerr := filepath.Rel(projectDir, p)
			if rerr != nil {
				return rerr
			}
			relSlash := oruby.NormalizeOrbPath(rel)
			if relSlash == "" {
				return nil
			}
			if !cfg.EmbedPublic && (relSlash == "public" || strings.HasPrefix(relSlash, "public/")) {
				if d.IsDir() {
					return filepath.SkipDir
				}
				return nil
			}
			if shouldExcludeRelPath(relSlash, d.IsDir(), cfg, gitRules) {
				if d.IsDir() {
					return filepath.SkipDir
				}
				return nil
			}
			if d.IsDir() {
				if relSlash == "lib" || strings.HasSuffix(relSlash, "/lib") {
					_ = builder.AddDir(relSlash, true)
				}
				return nil
			}
			if err := packFileWithVirtual(p, relSlash); err != nil {
				return err
			}
			packedFiles++
			return nil
		})
		if err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
	}

	// exe: the bundle runs where ORuby is not installed, with its libraries
	if strings.EqualFold(cfg.Target, "exe") {
		if err := packStdlib(builder, packFileWithVirtual); err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
	}
	if err := builder.WriteFile(absOut); err != nil {
		return exitFailure("%s build: cannot write %s: %v\n", prog, absOut, err)
	}
	if mArgs.gatheredBins > 0 || mArgs.gatheredLibs > 0 {
		outDir := filepath.Dir(cfg.Output)
		var extras []string
		if mArgs.gatheredBins > 0 {
			extras = append(extras, fmt.Sprintf("%d binaries -> %s", mArgs.gatheredBins, filepath.ToSlash(filepath.Join(outDir, "bin"))))
		}
		if mArgs.gatheredLibs > 0 {
			extras = append(extras, fmt.Sprintf("%d libraries -> %s", mArgs.gatheredLibs, filepath.ToSlash(filepath.Join(outDir, "lib"))))
		}
		fmt.Printf("Built %s (%d project files packed, %s)\n", cfg.Output, packedFiles, strings.Join(extras, ", "))
	} else {
		fmt.Printf("Built %s (%d project files packed)\n", cfg.Output, packedFiles)
	}

	// exe: one executable, ORuby with the gems' C and Go extensions compiled in
	// and the bundle embedded (binary.go)
	if strings.EqualFold(cfg.Target, "exe") {
		exe := strings.TrimSuffix(absOut, filepath.Ext(absOut))
		if err := buildProjectBinary(prog, projectDir, cfg, cfg.Gems.Groups, pol, absOut, exe, verbose); err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
		fmt.Printf("Built executable %s\n", exe)
	}
	if strings.EqualFold(cfg.Target, "native") || strings.EqualFold(cfg.Target, "go") {
		goOutDir := strings.TrimSuffix(absOut, filepath.Ext(absOut)) + "_go"
		if err := buildNativeProject(mrb, prog, projectDir, cfg, pol, absOut, goOutDir, verbose); err != nil {
			return exitFailure("%s build: %v\n", prog, err)
		}
		fmt.Printf("Generated Go AOT module in %s\n", goOutDir)
	}
	return 0
}
