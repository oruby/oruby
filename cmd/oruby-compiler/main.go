package main

import (
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/oruby/oruby"
	"github.com/oruby/oruby/compiler"
)

var (
	outFile    = flag.String("o", "", "Output Go source file path (or '-' for stdout)")
	pkgName    = flag.String("pkg", "main", "Target Go package name")
	buildBin   = flag.String("build", "", "Directly compile generated Go code into binary executable")
	disasmOnly = flag.Bool("disasm", false, "Disassemble bytecode and print without generating Go code")
	bundle     = flag.Bool("bundle", true, "Resolve, precompile, and bundle required ruby files")
	loadPath   = flag.String("I", "", "Colon/comma-separated directories to search for required files")
	target     = flag.String("target", "", "Cross-compile target (e.g. linux/amd64, linux/arm64)")
	docker     = flag.Bool("docker", false, "Compile Linux binary inside a Docker container")
	dockerfile = flag.String("dockerfile", "", "Generate multi-stage Dockerfile for containerized deployment")
	embedDirs  = flag.String("embed", "", "Optional comma-separated directories to embed via //go:embed (empty = files on disk)")
	verbose    = flag.Bool("v", false, "Verbose output")
)

func generateDockerfile(embed string, outPath string) error {
	content := `# Multi-stage Dockerfile for ORuby application
# Generated by oruby-compiler

FROM golang:1.27-bullseye AS builder

# Install build dependencies for mruby cgo
RUN apt-get update && apt-get install -y --no-install-recommends \
    git build-essential rake bison libreadline-dev && \
    rm -rf /var/lib/apt/lists/*

WORKDIR /app
COPY . .

# Build application
RUN go mod download && go build -o /app/server .

FROM debian:bullseye-slim
WORKDIR /app
RUN apt-get update && apt-get install -y --no-install-recommends \
    ca-certificates libreadline8 && \
    rm -rf /var/lib/apt/lists/*

COPY --from=builder /app/server /app/server
`
	if embed == "" {
		content += `# Static assets and views kept on disk for reverse proxy / CDN caching
COPY views /app/views
COPY public /app/public
`
	}
	content += `
EXPOSE 8080
ENTRYPOINT ["/app/server"]
`
	if outPath == "" || outPath == "-" {
		fmt.Print(content)
		return nil
	}
	return os.WriteFile(outPath, []byte(content), 0644)
}

func usage() {
	fmt.Fprintf(os.Stderr, "Usage: oruby-compiler [options] <file.rb>\n\nOptions:\n")
	flag.PrintDefaults()
}

func copyDir(src, dst string) error {
	return filepath.Walk(src, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if info.IsDir() {
			return os.MkdirAll(target, info.Mode())
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, info.Mode())
	})
}

func main() {
	flag.Usage = usage
	flag.Parse()

	if *dockerfile != "" && len(flag.Args()) == 0 {
		if err := generateDockerfile(*embedDirs, *dockerfile); err != nil {
			log.Fatalf("Error generating Dockerfile: %v\n", err)
		}
		if *verbose {
			fmt.Printf("Generated Dockerfile at %s\n", *dockerfile)
		}
		return
	}

	args := flag.Args()
	if len(args) == 0 {
		usage()
		os.Exit(1)
	}

	if *dockerfile != "" {
		if err := generateDockerfile(*embedDirs, *dockerfile); err != nil {
			log.Fatalf("Error generating Dockerfile: %v\n", err)
		}
		if *verbose {
			fmt.Printf("Generated Dockerfile at %s\n", *dockerfile)
		}
	}

	inputPath := args[0]
	var rubyCode []byte
	var err error

	if inputPath == "-" {
		rubyCode, err = io.ReadAll(os.Stdin)
	} else {
		rubyCode, err = os.ReadFile(inputPath)
	}
	if err != nil {
		log.Fatalf("Error reading input %s: %v\n", inputPath, err)
	}

	mrb := oruby.MrbOpen()
	if mrb == nil {
		log.Fatal("Failed to initialize mrb_state")
	}
	defer mrb.Close()

	cxt := mrb.MrbCcontextNew()
	defer cxt.Free()
	cxt.SetNoExec(true)
	cxt.Filename(inputPath)

	parser, err := mrb.ParseString(string(rubyCode), cxt)
	if err != nil {
		log.Fatalf("Ruby parse error: %v\n", err)
	}

	proc, err := mrb.GenerateCode(parser)
	if err != nil {
		log.Fatalf("Bytecode generation error: %v\n", err)
	}

	irep := proc.IRep()
	if irep.IsNil() {
		log.Fatal("Generated irep is empty")
	}

	if *disasmOnly {
		decoder := compiler.NewDecoder(mrb)
		unit, err := decoder.Decode(irep)
		if err != nil {
			log.Fatalf("Failed decoding bytecode: %v\n", err)
		}
		fmt.Println(unit.Disassemble())
		return
	}

	var embeds []string
	if *embedDirs != "" {
		for _, d := range strings.Split(*embedDirs, ",") {
			if trimmed := strings.TrimSpace(d); trimmed != "" {
				embeds = append(embeds, trimmed)
			}
		}
	}

	standalone := (*buildBin != "") || (*pkgName == "main")
	comp := compiler.New(compiler.Options{
		PackageName: *pkgName,
		Standalone:  standalone,
		EmbedDirs:   embeds,
	})

	var goSrc string
	if *bundle && inputPath != "-" {
		var lps []string
		if *loadPath != "" {
			for _, p := range strings.Split(*loadPath, ":") {
				if p != "" {
					lps = append(lps, strings.TrimSpace(p))
				}
			}
		}
		goSrc, err = comp.CompileBundle(mrb, inputPath, lps)
	} else {
		decoder := compiler.NewDecoder(mrb)
		unit, err := decoder.Decode(irep)
		if err != nil {
			log.Fatalf("Failed decoding bytecode: %v\n", err)
		}
		codegen := compiler.NewCodeGen(compiler.CodeGenOptions{
			PackageName: *pkgName,
			Standalone:  standalone,
			EmbedDirs:   embeds,
		})
		goSrc, err = codegen.Generate(unit)
	}

	if err != nil {
		log.Fatalf("Code generation error: %v\n", err)
	}

	// Direct compilation to binary requested
	if *buildBin != "" {
		tmpDir, err := os.MkdirTemp("", "oruby_build_*")
		if err != nil {
			log.Fatalf("Failed creating temp build dir: %v\n", err)
		}
		defer os.RemoveAll(tmpDir)

		srcFile := filepath.Join(tmpDir, "main.go")
		if err := os.WriteFile(srcFile, []byte(goSrc), 0644); err != nil {
			log.Fatalf("Failed writing temp source file: %v\n", err)
		}

		// Copy embedded directories if specified
		inputDir := filepath.Dir(inputPath)
		for _, ed := range embeds {
			srcDir := filepath.Join(inputDir, ed)
			if stat, err := os.Stat(srcDir); err == nil && stat.IsDir() {
				_ = copyDir(srcDir, filepath.Join(tmpDir, ed))
			} else if stat, err := os.Stat(ed); err == nil && stat.IsDir() {
				_ = copyDir(ed, filepath.Join(tmpDir, ed))
			}
		}

		// Initialize go.mod
		orubyPath := os.Getenv("ORUBY_PATH")
		if orubyPath == "" {
			cwd, _ := os.Getwd()
			for dir := cwd; dir != "/" && dir != ""; dir = filepath.Dir(dir) {
				if _, err := os.Stat(filepath.Join(dir, "go-mrb.h")); err == nil {
					orubyPath = dir
					break
				}
			}
		}

		modContent := "module app\n\ngo 1.27\n\nrequire github.com/oruby/oruby v0.0.0\n"
		if orubyPath != "" {
			modContent += fmt.Sprintf("replace github.com/oruby/oruby => %s\n", orubyPath)
			if sumBytes, err := os.ReadFile(filepath.Join(orubyPath, "go.sum")); err == nil {
				_ = os.WriteFile(filepath.Join(tmpDir, "go.sum"), sumBytes, 0644)
			}
		}
		_ = os.WriteFile(filepath.Join(tmpDir, "go.mod"), []byte(modContent), 0644)

		tidyCmd := exec.Command("go", "mod", "tidy")
		tidyCmd.Dir = tmpDir
		_ = tidyCmd.Run()

		absBin, err := filepath.Abs(*buildBin)
		if err != nil {
			log.Fatalf("Invalid binary path: %v\n", err)
		}

		// Check if Docker build is requested or needed for Linux target
		if *docker || (*target != "" && strings.HasPrefix(*target, "linux") && os.Getenv("USE_DOCKER") != "0") {
			if _, lookErr := exec.LookPath("docker"); lookErr == nil {
				arch := "amd64"
				if strings.Contains(*target, "arm64") {
					arch = "arm64"
				}
				dockerBuildCmd := exec.Command("docker", "run", "--rm",
					"-v", fmt.Sprintf("%s:/src", tmpDir),
					"-w", "/src",
					fmt.Sprintf("--platform=linux/%s", arch),
					"golang:1.27-bullseye",
					"sh", "-c", "go build -o /src/compiled_bin .")
				if out, err := dockerBuildCmd.CombinedOutput(); err == nil {
					_ = os.Rename(filepath.Join(tmpDir, "compiled_bin"), absBin)
					if *verbose {
						fmt.Printf("Successfully compiled for Linux (%s) via Docker -> %s\n", arch, absBin)
					}
					return
				} else if *verbose {
					fmt.Printf("Docker build failed, falling back to local compiler: %s\n", string(out))
				}
			}
		}

		buildCmd := exec.Command("go", "build", "-o", absBin, ".")
		buildCmd.Dir = tmpDir
		if *target != "" {
			parts := strings.Split(*target, "/")
			if len(parts) == 2 {
				buildCmd.Env = append(os.Environ(), "GOOS="+parts[0], "GOARCH="+parts[1])
			}
		}
		out, err := buildCmd.CombinedOutput()
		if err != nil {
			log.Fatalf("go build failed: %v\nOutput: %s\n", err, string(out))
		}

		if *verbose {
			fmt.Printf("Successfully compiled %s -> %s\n", inputPath, absBin)
		}
		return
	}

	// Write output Go source
	if *outFile == "" || *outFile == "-" {
		fmt.Print(goSrc)
	} else {
		if err := os.WriteFile(*outFile, []byte(goSrc), 0644); err != nil {
			log.Fatalf("Failed writing output file %s: %v\n", *outFile, err)
		}
		if *verbose {
			fmt.Printf("Wrote Go source to %s\n", *outFile)
		}
	}
}
